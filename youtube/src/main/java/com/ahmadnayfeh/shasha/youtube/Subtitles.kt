package com.ahmadnayfeh.shasha.youtube

/**
 * The subtitles a viewer can choose from ([StreamDetails.subtitles]): one per language, the ones a person wrote preferred over
 * YouTube's automatic ones of the same language, in the order of the list (human-made first, as [VideoSource.stream] gives them).
 */
fun List<SubtitleTrack>.perLanguage(): List<SubtitleTrack> =
    groupBy { it.languageCode.lowercase() }.values.map { same -> same.firstOrNull { !it.isAutoGenerated } ?: same.first() }

/**
 * The track of these that answers to the viewer's [language] (a [SubtitleTrack.languageCode] chosen before, perhaps for another
 * video): the same code, else the same language with another region ("en" for "en-GB", and the other way round), a human-made
 * track before an automatic one. Null for no [language] (subtitles off) and when the video has none in it.
 *
 * The playback factory takes the answer's [SubtitleTrack.languageCode] as its `subtitleLanguage`, and finds the same track.
 */
fun List<SubtitleTrack>.matching(language: String?): SubtitleTrack? {
    if (language.isNullOrBlank()) return null
    val choices = perLanguage()
    choices.firstOrNull { it.languageCode.equals(language, ignoreCase = true) }?.let { return it }
    val primary = language.substringBefore('-').lowercase()
    val sameLanguage = choices.filter { it.languageCode.substringBefore('-').lowercase() == primary }
    return sameLanguage.firstOrNull { !it.isAutoGenerated } ?: sameLanguage.firstOrNull()
}
