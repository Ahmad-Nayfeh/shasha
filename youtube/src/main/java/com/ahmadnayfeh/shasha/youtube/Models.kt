package com.ahmadnayfeh.shasha.youtube

data class ItemsPage(val items: List<SourceItem>, val next: PageKey?)

data class PlaylistPage(val details: PlaylistItem, val videos: List<VideoItem>, val next: PageKey?)

sealed interface SourceItem

data class VideoItem(
    val videoId: String,
    val title: String,
    val channelId: String?,
    val channelName: String?,
    /** Null when unknown (RSS items, live streams). */
    val durationSeconds: Long?,
    val publishedAtEpochMs: Long?,
    val thumbnailUrl: String?,
    val viewCount: Long?,
    val isLive: Boolean,
    /** Extractor short-form flag OR the url contains "/shorts/". */
    val isShortForm: Boolean,
    val url: String,
) : SourceItem

data class ChannelItem(
    val channelId: String,
    val name: String,
    val avatarUrl: String?,
    val subscriberCount: Long?,
) : SourceItem

data class PlaylistItem(
    val playlistId: String,
    val title: String,
    val channelName: String?,
    val thumbnailUrl: String?,
    val videoCount: Long?,
) : SourceItem

data class ChannelDetails(val channel: ChannelItem, val bannerUrl: String?, val description: String?)

data class StreamDetails(
    /** channelId is always filled here. */
    val video: VideoItem,
    val description: String?,
    /** For the quality menu, best first. Video-only (adaptive) tracks, or muxed ones when no adaptive exist. */
    val videoTracks: List<VideoTrack>,
    val subtitles: List<SubtitleTrack>,
    /** Opaque, consumed by the playback factory of this module. */
    val playback: PlaybackHandle,
)

data class VideoTrack(val height: Int, val fps: Int, val codec: String, val bitrate: Int)

data class SubtitleTrack(val languageCode: String, val label: String, val isAutoGenerated: Boolean)

sealed interface YouTubeLink {
    data class Video(val id: String, val startSeconds: Long?, val playlistId: String?) : YouTubeLink

    data class Playlist(val id: String) : YouTubeLink

    /**
     * [raw] is normalised to one of: "UC…" (a channel id), "@handle", "c/name", "user/name".
     * Only the first form is a channel id; use [VideoSource.resolveChannelId] for the others.
     */
    data class Channel(val raw: String) : YouTubeLink
}
