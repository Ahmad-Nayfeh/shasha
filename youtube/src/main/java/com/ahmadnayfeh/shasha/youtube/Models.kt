package com.ahmadnayfeh.shasha.youtube

data class ItemsPage(val items: List<SourceItem>, val next: PageKey?)

data class PlaylistPage(val details: PlaylistItem, val videos: List<VideoItem>, val next: PageKey?)

/**
 * One page of [VideoSource.searchShorts]: Shorts only (every item has [VideoItem.isShortForm] true, no channel, duration or
 * date: see there) and where the list continues ([next]; null at its end).
 */
data class ShortsPage(val shorts: List<VideoItem>, val next: PageKey?)

sealed interface SourceItem

data class VideoItem(
    val videoId: String,
    val title: String,
    val channelId: String?,
    val channelName: String?,
    /** Null when unknown (RSS items, live streams). */
    val durationSeconds: Long?,
    val publishedAtEpochMs: Long?,
    val thumbnailUrl: String?,
    val viewCount: Long?,
    val isLive: Boolean,
    /** Extractor short-form flag OR the url contains "/shorts/". */
    val isShortForm: Boolean,
    val url: String,
    /**
     * [publishedAtEpochMs] comes from a rounded text such as "2 weeks ago" (search, channel and playlist
     * pages): the upload may be up to one unit older. RSS dates are exact.
     */
    val publishedAtIsApproximate: Boolean = false,
    /**
     * A fragment of the video's description, when the list that gave this item carries one (search results do; YouTube shows
     * the part that matches the query). Never shown: [com.ahmadnayfeh.shasha.youtube.safety.SafeVideoSource] judges it.
     */
    val snippet: String? = null,
) : SourceItem

data class ChannelItem(
    val channelId: String,
    val name: String,
    val avatarUrl: String?,
    val subscriberCount: Long?,
    /** The start of the channel's description, in search results. Never shown: judged like [VideoItem.snippet]. */
    val snippet: String? = null,
) : SourceItem

data class PlaylistItem(
    val playlistId: String,
    val title: String,
    val channelName: String?,
    val thumbnailUrl: String?,
    val videoCount: Long?,
) : SourceItem

/**
 * The sections of a channel's page, as YouTube's channel tabs: its videos, its Shorts, its live streams (past, current
 * and scheduled) and its playlists. [VideoSource.channelTab] reads one of them.
 */
enum class ChannelTab {
    VIDEOS,
    SHORTS,
    LIVE,
    PLAYLISTS,
    ;

    /** The sections that list videos: the only ones that can be sorted ([ChannelSort]). The playlists are not. */
    val listsVideos: Boolean get() = this != PLAYLISTS
}

/** How a section of a channel is ordered. [LATEST] is YouTube's own order and the default. */
enum class ChannelSort { LATEST, POPULAR, OLDEST }

/**
 * One page of a channel's section ([VideoSource.channelTab]): [VideoItem]s, or [PlaylistItem]s in [ChannelTab.PLAYLISTS].
 *
 * [sorts] are the orders this section really offers, [ChannelSort.LATEST] first: only [ChannelSort.LATEST] where YouTube
 * gives no choice (a section with very few items, the playlists), and the same on every page of one section. A sort
 * that is not in it must not be offered: asking for it fails.
 */
data class ChannelTabPage(
    val items: List<SourceItem>,
    val next: PageKey?,
    val sorts: List<ChannelSort> = listOf(ChannelSort.LATEST),
)

/**
 * [tabs]: the sections the channel really has (fixed order: [ChannelTab.entries]). A source that cannot tell says only
 * [ChannelTab.VIDEOS], the page every channel has always shown.
 */
data class ChannelDetails(
    val channel: ChannelItem,
    val bannerUrl: String?,
    val description: String?,
    val tabs: List<ChannelTab> = listOf(ChannelTab.VIDEOS),
)

data class StreamDetails(
    /** channelId is always filled here. */
    val video: VideoItem,
    val description: String?,
    /** For the quality menu, best first. Video-only (adaptive) tracks, or muxed ones when no adaptive exist. */
    val videoTracks: List<VideoTrack>,
    val subtitles: List<SubtitleTrack>,
    /** Opaque, consumed by the playback factory of this module. */
    val playback: PlaybackHandle,
    /**
     * Null normally. Set only when [VideoSource.stream] was allowed to fall back to a low-quality muxed file and
     * had to (no adaptive ladder, no HLS): the height of the best such file (≤ 360), which is what plays. Show it.
     */
    val lowQualityHeight: Int? = null,
    /**
     * The picture of the channel that uploaded the video, from the video's own page: a subscription made from the player
     * screen stores it. Null when the page has none. It needs no request of its own, so it is there also where
     * [VideoSource.channel] fails for the same channel (a network that answers the channel's page with an error).
     */
    val uploaderAvatarUrl: String? = null,
)

data class VideoTrack(val height: Int, val fps: Int, val codec: String, val bitrate: Int)

data class SubtitleTrack(val languageCode: String, val label: String, val isAutoGenerated: Boolean)

sealed interface YouTubeLink {
    data class Video(val id: String, val startSeconds: Long?, val playlistId: String?) : YouTubeLink

    data class Playlist(val id: String) : YouTubeLink

    /**
     * [raw] is normalised to one of: "UC…" (a channel id), "@handle", "c/name", "user/name".
     * Only the first form is a channel id; use [VideoSource.resolveChannelId] for the others.
     */
    data class Channel(val raw: String) : YouTubeLink
}
