package com.ahmadnayfeh.shasha.youtube.newpipe

import com.ahmadnayfeh.shasha.youtube.ChannelItem
import com.ahmadnayfeh.shasha.youtube.PlaylistItem
import com.ahmadnayfeh.shasha.youtube.SourceItem
import com.ahmadnayfeh.shasha.youtube.VideoItem
import com.ahmadnayfeh.shasha.youtube.YouTubeLinkParser
import org.schabi.newpipe.extractor.Image
import org.schabi.newpipe.extractor.InfoItem
import org.schabi.newpipe.extractor.channel.ChannelInfoItem
import org.schabi.newpipe.extractor.localization.DateWrapper
import org.schabi.newpipe.extractor.playlist.PlaylistInfo
import org.schabi.newpipe.extractor.playlist.PlaylistInfoItem
import org.schabi.newpipe.extractor.stream.StreamInfoItem
import org.schabi.newpipe.extractor.stream.StreamType

/** NewPipeExtractor models → our public models. Items we cannot identify are dropped. */
internal object ItemMapper {

    /** Card thumbnails on a 1080p TV are ~480 px wide. */
    private const val THUMBNAIL_WIDTH = 480
    private const val AVATAR_WIDTH = 176
    private const val BANNER_WIDTH = 1280

    fun toSourceItem(item: InfoItem): SourceItem? = when (item) {
        is StreamInfoItem -> toVideo(item)
        is ChannelInfoItem -> toChannel(item)
        // Mixes are generated by YouTube's recommendation algorithm: not shown in this app.
        is PlaylistInfoItem -> if (item.playlistType == PlaylistInfo.PlaylistType.NORMAL) toPlaylist(item) else null
        else -> null
    }

    /**
     * @param exactDates the item's date is a timestamp (RSS), not a rounded text such as "2 weeks ago" (search,
     *   channel and playlist pages), which NewPipe turns into the newest time it allows.
     */
    fun toVideo(
        item: StreamInfoItem,
        fallbackChannelId: String? = null,
        fallbackChannelName: String? = null,
        exactDates: Boolean = false,
    ): VideoItem? {
        val url = item.url ?: return null
        val videoId = YouTubeLinkParser.videoIdFromUrl(url) ?: return null
        return VideoItem(
            videoId = videoId,
            title = item.name.orEmpty(),
            channelId = YouTubeLinkParser.channelIdFromUrl(item.uploaderUrl) ?: fallbackChannelId,
            channelName = item.uploaderName?.takeIf { it.isNotBlank() } ?: fallbackChannelName,
            durationSeconds = item.duration.positiveOrNull(),
            publishedAtEpochMs = item.uploadDate.epochMs(),
            thumbnailUrl = bestImage(item.thumbnails, THUMBNAIL_WIDTH),
            viewCount = item.viewCount.nonNegativeOrNull(),
            isLive = item.streamType.isLive(),
            isShortForm = item.isShortFormContent || isShortsUrl(url),
            url = url,
            publishedAtIsApproximate = !exactDates,
        )
    }

    fun toChannel(item: ChannelInfoItem): ChannelItem? {
        val channelId = YouTubeLinkParser.channelIdFromUrl(item.url) ?: return null
        return ChannelItem(
            channelId = channelId,
            name = item.name.orEmpty(),
            avatarUrl = bestImage(item.thumbnails, AVATAR_WIDTH),
            subscriberCount = item.subscriberCount.nonNegativeOrNull(),
        )
    }

    fun toPlaylist(item: PlaylistInfoItem): PlaylistItem? {
        val playlistId = YouTubeLinkParser.playlistIdFromUrl(item.url) ?: return null
        return PlaylistItem(
            playlistId = playlistId,
            title = item.name.orEmpty(),
            channelName = item.uploaderName?.takeIf { it.isNotBlank() },
            thumbnailUrl = bestImage(item.thumbnails, THUMBNAIL_WIDTH),
            videoCount = item.streamCount.nonNegativeOrNull(),
        )
    }

    fun avatar(images: List<Image>?) = bestImage(images, AVATAR_WIDTH)

    fun banner(images: List<Image>?) = bestImage(images, BANNER_WIDTH)

    fun thumbnail(images: List<Image>?) = bestImage(images, THUMBNAIL_WIDTH)

    /** Smallest image at least [targetWidth] wide; else the largest; unknown sizes → last (YouTube lists small → big). */
    fun bestImage(images: List<Image>?, targetWidth: Int): String? {
        if (images.isNullOrEmpty()) return null
        val sized = images.filter { it.width > 0 }
        if (sized.isEmpty()) return images.last().url
        return (sized.filter { it.width >= targetWidth }.minByOrNull { it.width } ?: sized.maxBy { it.width }).url
    }

    fun isShortsUrl(url: String?) = url?.contains("/shorts/") == true

    fun StreamType?.isLive() = this == StreamType.LIVE_STREAM || this == StreamType.AUDIO_LIVE_STREAM

    fun DateWrapper?.epochMs(): Long? = runCatching { this?.instant?.toEpochMilli() }.getOrNull()

    fun Long.positiveOrNull(): Long? = takeIf { it > 0 }

    fun Long.nonNegativeOrNull(): Long? = takeIf { it >= 0 }
}
