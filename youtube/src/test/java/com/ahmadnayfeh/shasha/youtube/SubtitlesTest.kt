package com.ahmadnayfeh.shasha.youtube

import com.google.common.truth.Truth.assertThat
import org.junit.Test

/** Which subtitles a video offers to choose from, and which of them answers to the language the viewer chose before. */
class SubtitlesTest {
    private val arabic = SubtitleTrack("ar", "Arabic", isAutoGenerated = false)
    private val englishAuto = SubtitleTrack("en", "English", isAutoGenerated = true)
    private val english = SubtitleTrack("en", "English", isAutoGenerated = false)
    private val british = SubtitleTrack("en-GB", "English (United Kingdom)", isAutoGenerated = false)
    private val frenchAuto = SubtitleTrack("fr", "French", isAutoGenerated = true)

    @Test
    fun oneChoicePerLanguage_whatAPersonWroteBeforeYouTubesAutomaticOnes() {
        assertThat(listOf(englishAuto, arabic, english, frenchAuto).perLanguage()).containsExactly(english, arabic, frenchAuto).inOrder()
    }

    @Test
    fun theLanguageChosenBeforeFindsItsTrack_orTheSameLanguageOfAnotherRegion() {
        val tracks = listOf(arabic, english, frenchAuto)
        assertThat(tracks.matching("ar")).isEqualTo(arabic)
        assertThat(tracks.matching("EN")).isEqualTo(english)
        assertThat(tracks.matching("en-GB")).isEqualTo(english)
        assertThat(listOf(british).matching("en")).isEqualTo(british)
        assertThat(tracks.matching("fr")).isEqualTo(frenchAuto)
    }

    @Test
    fun noLanguageOrOneTheVideoDoesNotHaveMeansNoSubtitles() {
        assertThat(listOf(arabic, english).matching(null)).isNull()
        assertThat(listOf(arabic, english).matching("")).isNull()
        assertThat(listOf(arabic, english).matching("de")).isNull()
        assertThat(emptyList<SubtitleTrack>().matching("en")).isNull()
    }
}
