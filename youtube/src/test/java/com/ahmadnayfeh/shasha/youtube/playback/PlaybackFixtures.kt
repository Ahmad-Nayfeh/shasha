package com.ahmadnayfeh.shasha.youtube.playback

import com.ahmadnayfeh.shasha.youtube.PlaybackHandle
import com.ahmadnayfeh.shasha.youtube.StreamDetails
import com.ahmadnayfeh.shasha.youtube.VideoItem
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.services.youtube.ItagItem
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.AudioTrackType
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamType
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import org.schabi.newpipe.extractor.stream.VideoStream
import java.util.Locale

/** NewPipeExtractor objects shaped like what YoutubeStreamExtractor returns. */
internal object PlaybackFixtures {

    const val VIDEO_ID = "dQw4w9WgXcQ"
    const val DURATION_MS = 212_091L

    fun url(itag: Int, client: String = "ANDROID") =
        "https://rr1---sn-test.googlevideo.com/videoplayback?expire=1&id=o-AB&itag=$itag&source=youtube&c=$client&sig=AB%3D%3D&n=x"

    fun videoOnly(
        itag: Int,
        codec: String,
        width: Int,
        height: Int,
        fps: Int = 30,
        bitrate: Int = height * 2_000,
        ranges: Boolean = true,
        otf: Boolean = false,
        postLive: Boolean = false,
    ): VideoStream {
        val item = ItagItem.getItag(itag).apply {
            setCodec(codec)
            setWidth(width)
            setHeight(height)
            setFps(fps)
            setBitrate(bitrate)
            setRanges(ranges)
            setApproxDurationMs(DURATION_MS)
            if (postLive) setTargetDurationSec(5)
        }
        return VideoStream.Builder()
            .setId(itag.toString())
            .setContent(url(itag), !otf && !postLive)
            .setMediaFormat(item.mediaFormat)
            .setIsVideoOnly(true)
            .setResolution(item.getResolutionString() ?: "${height}p")
            .setItagItem(item)
            .apply { if (otf || postLive) setDeliveryMethod(DeliveryMethod.DASH) }
            .build()
    }

    fun audio(
        itag: Int,
        codec: String,
        bitrate: Int,
        trackId: String? = null,
        type: AudioTrackType? = null,
        drc: Boolean = false,
        ranges: Boolean = true,
    ): AudioStream {
        val item = ItagItem.getItag(itag).apply {
            setCodec(codec)
            setBitrate(bitrate)
            setSampleRate(if (codec == "opus") 48_000 else 44_100)
            setAudioChannels(2)
            setRanges(ranges)
            setApproxDurationMs(DURATION_MS)
            setIsDrc(drc)
            setAudioTrackId(trackId)
            setAudioTrackType(type)
            trackId?.let { setAudioLocale(Locale.forLanguageTag(it.substringBefore('.'))) }
        }
        return AudioStream.Builder()
            .setId(itag.toString())
            .setContent(url(itag) + (if (drc) "&drc=1" else "") + (trackId?.let { "&xtags=$it" } ?: ""), true)
            .setMediaFormat(item.mediaFormat)
            .setAverageBitrate(item.averageBitrate)
            .setAudioTrackId(trackId)
            .setAudioTrackType(type)
            .setAudioLocale(item.audioLocale)
            .setItagItem(item)
            .build()
    }

    fun muxed(itag: Int = 18, height: Int = 360): VideoStream {
        val item = ItagItem.getItag(itag).apply {
            setCodec("avc1.42001E, mp4a.40.2")
            setHeight(height)
            setWidth(height * 16 / 9)
            setBitrate(500_000)
        }
        return VideoStream.Builder()
            .setId(itag.toString())
            .setContent(url(itag), true)
            .setMediaFormat(item.mediaFormat)
            .setIsVideoOnly(false)
            .setResolution("${height}p")
            .setItagItem(item)
            .build()
    }

    fun subtitle(language: String, auto: Boolean, format: MediaFormat = MediaFormat.TTML): SubtitlesStream =
        SubtitlesStream.Builder()
            .setContent("https://www.youtube.com/api/timedtext?v=$VIDEO_ID&lang=$language${if (auto) "&kind=asr" else ""}&fmt=${format.suffix}", true)
            .setMediaFormat(format)
            .setLanguageCode(language)
            .setAutoGenerated(auto)
            .build()

    fun info(
        videoOnly: List<VideoStream> = standardLadder(),
        audio: List<AudioStream> = standardAudio(),
        muxed: List<VideoStream> = listOf(muxed()),
        type: StreamType = StreamType.VIDEO_STREAM,
        hls: String = "",
        dash: String = "",
        subtitles: List<SubtitlesStream> = emptyList(),
    ) = StreamInfo(
        ServiceList.YouTube.serviceId, "https://www.youtube.com/watch?v=$VIDEO_ID", "https://www.youtube.com/watch?v=$VIDEO_ID",
        type, VIDEO_ID, "Never Gonna Give You Up", 0,
    ).apply {
        videoOnlyStreams = videoOnly
        audioStreams = audio
        videoStreams = muxed
        hlsUrl = hls
        dashMpdUrl = dash
        duration = DURATION_MS / 1000
        this.subtitles = subtitles
    }

    fun details(info: StreamInfo) = StreamDetails(
        video = VideoItem(
            videoId = info.id, title = info.name, channelId = "UCuAXFkgsw1L7xaCfnd5JJOw", channelName = "Rick Astley",
            durationSeconds = info.duration, publishedAtEpochMs = null, thumbnailUrl = null, viewCount = null,
            isLive = info.streamType == StreamType.LIVE_STREAM, isShortForm = false, url = info.url,
        ),
        description = null,
        videoTracks = emptyList(),
        subtitles = emptyList(),
        playback = PlaybackHandle(info),
    )

    /** What VISIONOS returns for a normal video: H.264 and VP9 from 144p to 2160p. */
    fun standardLadder() = listOf(
        videoOnly(313, "vp9", 3840, 2160, bitrate = 17_000_000),
        videoOnly(271, "vp9", 2560, 1440, bitrate = 9_000_000),
        videoOnly(137, "avc1.640028", 1920, 1080, bitrate = 4_400_000),
        videoOnly(248, "vp9", 1920, 1080, bitrate = 2_600_000),
        videoOnly(136, "avc1.4d401f", 1280, 720, bitrate = 2_300_000),
        videoOnly(247, "vp9", 1280, 720, bitrate = 1_500_000),
        videoOnly(135, "avc1.4d401e", 854, 480, bitrate = 1_100_000),
        videoOnly(244, "vp9", 854, 480, bitrate = 800_000),
        videoOnly(160, "avc1.4d400c", 256, 144, bitrate = 110_000),
    )

    fun standardAudio() = listOf(
        audio(139, "mp4a.40.5", 49_000),
        audio(140, "mp4a.40.2", 130_000),
        audio(251, "opus", 150_000),
        audio(250, "opus", 80_000),
    )

    private fun ItagItem.setRanges(present: Boolean) {
        if (present) {
            initStart = 0
            initEnd = 740
            indexStart = 741
            indexEnd = 1296
        } else {
            initStart = -1
            initEnd = -1
            indexStart = -1
            indexEnd = -1
        }
    }
}
