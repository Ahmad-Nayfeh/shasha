package com.ahmadnayfeh.shasha.player

import com.ahmadnayfeh.shasha.youtube.SubtitleTrack
import com.google.common.truth.Truth.assertThat
import org.junit.Test

class PlaybackModelsTest {
    @Test
    fun qualityRungUsesTheShortSide() {
        assertThat(qualityRung(1080)).isEqualTo(1080)
        assertThat(qualityRung(1072)).isEqualTo(1080)
        assertThat(qualityRung(608)).isEqualTo(720)
        assertThat(qualityRung(360)).isEqualTo(360)
    }

    @Test
    fun qualityOptionsKeepOnlyTheMenuLadder() {
        assertThat(qualityOptions(listOf(2160, 1440, 1080, 720, 480, 360, 240, 144))).containsExactly(1080, 720, 480, 360).inOrder()
        assertThat(qualityOptions(listOf(720, 360))).containsExactly(720, 360).inOrder()
        assertThat(qualityOptions(emptyList())).isEmpty()
    }

    @Test
    fun subtitleOptionsPreferHumanMadeTracks() {
        val options = subtitleOptions(
            listOf(
                SubtitleTrack("en", "English (auto-generated)", isAutoGenerated = true),
                SubtitleTrack("en", "English", isAutoGenerated = false),
                SubtitleTrack("ar", "العربية", isAutoGenerated = false),
            ),
        )
        assertThat(options).containsExactly(
            SubtitleOption("en", "English", false),
            SubtitleOption("ar", "العربية", false),
        ).inOrder()
    }

    @Test
    fun durationsUseWesternDigits() {
        assertThat(formatDuration(0)).isEqualTo("0:00")
        assertThat(formatDuration(213_400)).isEqualTo("3:33")
        assertThat(formatDuration(3_729_000)).isEqualTo("1:02:09")
        assertThat(formatDuration(-5)).isEqualTo("0:00")
    }

    @Test
    fun speedsReadNaturally() {
        assertThat(formatSpeed(1f)).isEqualTo("1x")
        assertThat(formatSpeed(0.5f)).isEqualTo("0.5x")
        assertThat(formatSpeed(1.25f)).isEqualTo("1.25x")
        assertThat(formatSpeed(2f)).isEqualTo("2x")
    }
}
