package com.ahmadnayfeh.shasha.player

import androidx.compose.runtime.Immutable
import com.ahmadnayfeh.shasha.youtube.SubtitleTrack
import kotlin.math.abs

/** What the user picked in the quality menu. */
sealed interface QualityChoice {
    /** Adaptive (ABR) inside the ladder, capped at [MAX_AUTO_HEIGHT]. */
    data object Auto : QualityChoice

    /** One fixed rung of [QUALITY_LADDER] (YouTube's "720p" = the short side of the picture). */
    data class Fixed(val height: Int) : QualityChoice
}

data class SubtitleOption(val languageCode: String, val label: String, val isAutoGenerated: Boolean)

/** Everything the on-screen controls show. Plain data: the OSD can be rendered without a player. */
@Immutable
data class PlayerUiState(
    val title: String,
    val channelName: String?,
    val isLive: Boolean,
    val isPlaying: Boolean = false,
    /** The user wants playback (it may still be buffering). Drives the play/pause icon. */
    val playWhenReady: Boolean = true,
    /** Waiting for data (first load, after a seek, or a stall). */
    val isBuffering: Boolean = true,
    val isEnded: Boolean = false,
    val quality: QualityChoice = QualityChoice.Auto,
    /** Rungs of [QUALITY_LADDER] this video offers on this TV, best first. */
    val qualityOptions: List<Int> = emptyList(),
    /** Short side of the picture being shown now, when known. */
    val currentHeight: Int? = null,
    val speed: Float = 1f,
    val subtitleOptions: List<SubtitleOption> = emptyList(),
    /** Language code of the subtitles shown, null = off. */
    val subtitleLanguage: String? = null,
    /** Subtitle text to show now (already joined), null when nothing is on screen. */
    val cueText: String? = null,
)

data class PlaybackProgress(val positionMs: Long, val bufferedMs: Long, val durationMs: Long) {
    companion object {
        val Zero = PlaybackProgress(0, 0, 0)
    }
}

sealed interface PlayerAction {
    data object TogglePlayPause : PlayerAction
    data object Play : PlayerAction
    data object Pause : PlayerAction
    data class SeekTo(val positionMs: Long) : PlayerAction
    data class SetQuality(val choice: QualityChoice) : PlayerAction
    data class SetSpeed(val speed: Float) : PlayerAction
    data class SetSubtitle(val languageCode: String?) : PlayerAction
}

/** Where to continue after the player was released (app sent to the background) and the choices made. */
data class ResumeState(
    val positionMs: Long = 0,
    val playWhenReady: Boolean = true,
    val quality: QualityChoice = QualityChoice.Auto,
    val speed: Float = 1f,
    val subtitleLanguage: String? = null,
)

/** The quality cap of "Auto" (SPEC: prefer 1080p and fall back automatically). */
const val MAX_AUTO_HEIGHT = 1080

/** Fixed qualities offered in the menu, best first. */
val QUALITY_LADDER = listOf(1080, 720, 480, 360)

val PLAYBACK_SPEEDS = listOf(0.5f, 0.75f, 1f, 1.25f, 1.5f, 1.75f, 2f)

const val SEEK_STEP_MS = 10_000L

private val STANDARD_HEIGHTS = listOf(144, 240, 360, 480, 720, 1080, 1440, 2160, 4320)

/** Maps a picture's short side to YouTube's quality name (e.g. 1072 → 1080, 1920x1080 vertical → 1080). */
fun qualityRung(shortSide: Int): Int = STANDARD_HEIGHTS.minBy { abs(it - shortSide) }

/** The menu's fixed options for a video whose playable tracks have these short sides. */
fun qualityOptions(shortSides: Collection<Int>): List<Int> {
    val rungs = shortSides.filter { it > 0 }.map(::qualityRung).toSet()
    return QUALITY_LADDER.filter { it in rungs }
}

/**
 * One entry per language: human-made subtitles win over auto-generated ones for the same language
 * (the playback factory makes the same choice when it loads a language).
 */
fun subtitleOptions(tracks: List<SubtitleTrack>): List<SubtitleOption> =
    tracks.groupBy { it.languageCode }
        .map { (code, sameLanguage) ->
            val best = sameLanguage.firstOrNull { !it.isAutoGenerated } ?: sameLanguage.first()
            SubtitleOption(code, best.label.ifBlank { code }, best.isAutoGenerated)
        }

/** "3:07", "1:02:09"; Western digits as everywhere in the app. */
fun formatDuration(ms: Long): String {
    val totalSeconds = (ms.coerceAtLeast(0) / 1000)
    val h = totalSeconds / 3600
    val m = (totalSeconds % 3600) / 60
    val s = totalSeconds % 60
    return if (h > 0) "%d:%02d:%02d".format(java.util.Locale.ROOT, h, m, s) else "%d:%02d".format(java.util.Locale.ROOT, m, s)
}

fun formatSpeed(speed: Float): String {
    val text = if (speed == speed.toInt().toFloat()) speed.toInt().toString() else speed.toString().trimEnd('0')
    return "${text}x"
}
