enum class OsdMenu { QUALITY, SPEED, SUBTITLES }

internal data class MenuOption(val label: String, val selected: Boolean, val action: PlayerAction)

@Composable
internal fun menuTitle(menu: OsdMenu): String = stringResource(
    when (menu) {
        OsdMenu.QUALITY -> R.string.player_quality
        OsdMenu.SPEED -> R.string.player_speed
        OsdMenu.SUBTITLES -> R.string.player_subtitles
    },
)

internal fun menuIcon(menu: OsdMenu) = when (menu) {
    OsdMenu.QUALITY -> ShashaIcons.Tune
    OsdMenu.SPEED -> ShashaIcons.Speed
    OsdMenu.SUBTITLES -> ShashaIcons.Subtitles
}

@Composable
internal fun menuOptions(menu: OsdMenu, state: PlayerUiState): List<MenuOption> = when (menu) {
    OsdMenu.QUALITY -> buildList {
        val auto = stringResource(R.string.player_quality_auto_detail, state.autoQualityCap.toString())
        add(MenuOption(auto, state.quality == QualityChoice.Auto, PlayerAction.SetQuality(QualityChoice.Auto)))
        state.qualityOptions.forEach { h ->
            add(MenuOption("${h}p", state.quality == QualityChoice.Fixed(h), PlayerAction.SetQuality(QualityChoice.Fixed(h))))
        }
    }
    OsdMenu.SPEED -> PLAYBACK_SPEEDS.map { speed ->
        val label = if (speed == 1f) "${stringResource(R.string.player_speed_normal)} (${formatSpeed(speed)})" else formatSpeed(speed)
        MenuOption(label, state.speed == speed, PlayerAction.SetSpeed(speed))
    }
    OsdMenu.SUBTITLES -> buildList {
        add(MenuOption(stringResource(R.string.player_subtitles_off), state.subtitleLanguage == null, PlayerAction.SetSubtitle(null)))
        state.subtitleOptions.forEach { option ->
            val label = if (option.isAutoGenerated) stringResource(R.string.player_subtitles_auto, option.label) else option.label
            add(MenuOption(label, state.subtitleLanguage == option.languageCode, PlayerAction.SetSubtitle(option.languageCode)))
        }
    }
}

/**
 * Side panel for one menu, on the right (the start side in Arabic). Focus starts on the current
 * choice and cannot wander out of the panel; BACK closes it (handled by PlayerOsd).
 */
@Composable
internal fun OsdMenuPanel(
    menu: OsdMenu,
    state: PlayerUiState,
    onSelect: (PlayerAction) -> Unit,
    modifier: Modifier = Modifier,
    trapFocus: Boolean = true,
) {
    val options = menuOptions(menu, state)
    val selectedIndex = options.indexOfFirst { it.selected }.coerceAtLeast(0)
    val requesters = remember(menu, options.size) { List(options.size) { FocusRequester() } }
    val listState = rememberLazyListState(initialFirstVisibleItemIndex = (selectedIndex - 2).coerceAtLeast(0))
    LaunchedEffect(menu) {
        withFrameNanos { }
        runCatching { requesters[selectedIndex].requestFocus() }
    }
    val shape = RoundedCornerShape(24.dp)
    Column(
        modifier
            .width(340.dp)
            .shadow(24.dp, shape, ambientColor = Color.Black, spotColor = Color.Black)
            .background(ShashaColors.Surface, shape)
            .border(1.dp, ShashaColors.Outline, shape)
            .padding(top = 22.dp, bottom = 14.dp)
            .testTag("osd_menu"),
    ) {
        Row(Modifier.padding(horizontal = 28.dp), verticalAlignment = Alignment.CenterVertically) {
            Icon(menuIcon(menu), contentDescription = null, tint = LocalAccent.current.main, modifier = Modifier.size(26.dp))
            Spacer(Modifier.width(12.dp))
            Text(menuTitle(menu), style = MaterialTheme.typography.headlineSmall)
        }
        Spacer(Modifier.height(10.dp))
        LazyColumn(
            state = listState,
            contentPadding = PaddingValues(horizontal = 16.dp, vertical = 8.dp),
            verticalArrangement = Arrangement.spacedBy(6.dp),
            modifier = Modifier
                .heightIn(max = 360.dp)
                .focusProperties { onExit = { if (trapFocus) cancelFocusChange() } }
                .focusGroup(),
        ) {
            itemsIndexed(options) { index, option ->
                MenuOptionRow(option, onClick = { onSelect(option.action) }, modifier = Modifier.focusRequester(requesters[index]))
            }
        }
    }
}

@Composable
private fun MenuOptionRow(option: MenuOption, onClick: () -> Unit, modifier: Modifier = Modifier) {
    val accent = LocalAccent.current
    FocusSurface(
        onClick = onClick,
        modifier = modifier.fillMaxWidth().height(52.dp),
        shape = RoundedCornerShape(14.dp),
        containerColor = ShashaColors.Surface.copy(alpha = 0f),
        focusedContainerColor = ShashaColors.SurfaceHigh,
        scale = 1.03f,
    ) {
        Row(
            Modifier.fillMaxWidth().align(Alignment.CenterStart).padding(horizontal = 14.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            Box(Modifier.size(26.dp), contentAlignment = Alignment.Center) {
                if (option.selected) Icon(ShashaIcons.Check, contentDescription = null, tint = accent.main, modifier = Modifier.size(24.dp))
            }
            Spacer(Modifier.width(12.dp))
            Text(
                option.label,
                style = MaterialTheme.typography.titleMedium,
                color = if (option.selected) accent.bright else ShashaColors.Text,
                maxLines = 1,
                overflow = TextOverflow.Ellipsis,
            )
        }
    }
}
