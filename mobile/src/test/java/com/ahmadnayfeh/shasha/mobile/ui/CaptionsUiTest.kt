/**
 * Captions on the phone's player: the button over the video when the video has some, the choice in the player's settings (off,
 * or a language, YouTube's own ones marked), what is said drawn over the picture, and the choice kept for the next videos.
 */
@RunWith(AndroidJUnit4::class)
@Config(sdk = [35], application = MobileApp::class, qualifiers = "en-$PHONE")
class CaptionsUiTest {
    @get:Rule
    val compose = createComposeRule()

    private val app: Application get() = ApplicationProvider.getApplicationContext()

    private val withCaptions: PlayerUiState = Samples.playerState.copy(
        subtitles = listOf(SubtitleTrack("en", "الإنجليزية", isAutoGenerated = false), SubtitleTrack("ar", "العربية", isAutoGenerated = true)),
        subtitleLanguage = "en",
        cueText = "Black holes bend light",
    )

    private fun show(state: PlayerUiState) {
        compose.setContent {
            ShashaTheme(AppTheme.SYSTEM) {
                Surface(Modifier.fillMaxSize()) {
                    WatchContent(
                        state = state,
                        player = FakePlayer(),
                        controller = app.container.player,
                        details = FakeDetails(),
                        isFullscreen = false,
                        inPip = false,
                        onRetry = {},
                        onBack = {},
                        onToggleFullscreen = {},
                        onEnterPictureInPicture = null,
                        onVideoBounds = {},
                        onOpenVideo = {},
                        onOpenChannel = {},
                    )
                }
            }
        }
    }

    @Test
    fun whatIsSaidIsDrawnOverThePicture_andTheButtonOpensTheChoiceOfLanguages() {
        show(withCaptions)

        compose.onNodeWithText("Black holes bend light").assertIsDisplayed()
        compose.onNodeWithContentDescription("Captions").performClick()

        compose.onNodeWithText("Off").performScrollTo().assertIsDisplayed()
        // Named in the app's language, not in YouTube's Arabic labels; YouTube's own captions are marked.
        compose.onNodeWithText("English").performScrollTo().assertIsDisplayed()
        compose.onNodeWithText("Arabic (auto-generated)").performScrollTo().assertIsDisplayed()
    }

    @Test
    fun theChoiceIsKeptForTheNextVideos() {
        show(withCaptions)
        compose.onNodeWithContentDescription("Captions").performClick()

        compose.onNodeWithText("Arabic (auto-generated)").performScrollTo().performClick()

        compose.awaitCondition { runBlocking { app.container.settings.settings.first().subtitleLanguage } == "ar" }
    }

    @Test
    fun aVideoWithoutCaptionsHasNoButton_andItsSettingsSaySo() {
        show(Samples.playerState)

        compose.onNodeWithContentDescription("Captions").assertDoesNotExist()
        compose.onNodeWithContentDescription("Player settings").performClick()
        compose.onNodeWithText("This video has no captions.").performScrollTo().assertIsDisplayed()
    }

    @Test
    fun aLanguageIsNamedInTheAppsLanguage_elseByYouTubesLabel() {
        assertThat(captionName(SubtitleTrack("en", "الإنجليزية", false), Locale.ENGLISH)).isEqualTo("English")
        assertThat(captionName(SubtitleTrack("en", "English", false), Locale.forLanguageTag("ar"))).isEqualTo("الإنجليزية")
        assertThat(captionName(SubtitleTrack("zzz", "Klingon", false), Locale.ENGLISH)).isEqualTo("Klingon")
    }
}
